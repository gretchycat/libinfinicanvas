#!/usr/bin/env python3
"""Build the CP437 table from public domain font8x8 and explicit extra glyphs."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
lookup = {}
for path in sorted((ROOT / 'third_party/font8x8').glob('*.h')):
    for line in path.read_text().splitlines():
        match = re.search(r'\{([^}]+)\}.*U\+([0-9A-Fa-f]{4})', line)
        if match:
            values = re.findall(r'0x([0-9A-Fa-f]{2})', match[1])
            assert len(values) == 8
            lookup[int(match[2], 16)] = ''.join(values).lower()
# Original 8x8 drawings for DOS graphic controls and math not covered by font8x8.
extra = {
    1:'3c4281a58199423c', 2:'3c7effdbffe77e3c', 3:'006cfe7c38100000',
    4:'0010387c38100000', 5:'00183c7e7e183c00', 6:'10387cfe7c103800',
    7:'0000183c3c180000', 8:'ffffe7c3c3e7ffff', 9:'00003c42423c0000',
    10:'ffffc3bdbdc3ffff', 11:'780a3a4444380000', 12:'38444438107c1000',
    13:'30705010101c1c00', 14:'60785848486e6e00', 15:'105438ee38541000',
    16:'02060e1e0e060200', 17:'4020707870204000', 18:'1038541054381000',
    19:'2424242400240000', 20:'fc96969490909000', 21:'3c063c66663c603c',
    22:'0000007e7e000000', 23:'10385410547c0000', 24:'1038541010101000',
    25:'1010101054381000', 26:'0010207f20100000', 27:'0008047f04080000',
    28:'000202027e000000', 29:'002442ff42240000', 30:'0010387cfe000000',
    31:'00fe7c3810000000', 127:'0010386c44447c00',
    0xec:'0000669999660000', 0xef:'003c666666660000', 0xf0:'007e007e007e0000',
    0xf2:'0c1830180c003e00', 0xf3:'30180c1830003e00', 0xf4:'386c0c0c0c0c0c0c',
    0xf5:'3030303030361c00', 0xf7:'006c36006c360000', 0xf9:'0000001818000000',
    0xfb:'e02020242c381000', 0xfc:'001c242424000000', 0xfe:'00007e7e7e7e0000',
}
rows = []
for code in range(256):
    glyph = extra.get(code, lookup.get(ord(bytes([code]).decode('cp437'))))
    assert glyph is not None, code
    if code not in (0, 32, 255):
        assert int(glyph, 16) != 0, code
    rows.append(f'        "{glyph}", // 0x{code:02X}')
output = ROOT / 'canvas-android/src/main/java/com/infinifolder/preview/Cp437Font.kt'
output.write_text('''package com.infinifolder.preview

/** Real CP437 bitmap glyphs. Generated by scripts/generate-cp437-font.py.
 * Public domain font8x8 with original supplementary glyphs; see third_party/font8x8/PROVENANCE.md.
 * Eight rows, least significant bit at left, doubled vertically for 8x16 cells.
 */
internal object Cp437Font {
    private val glyphs = arrayOf(
''' + '\n'.join(rows) + '''
    ).map { hex -> IntArray(8) { row -> hex.substring(row * 2, row * 2 + 2).toInt(16) } }

    fun isForeground(code: Int, x: Int, y: Int): Boolean =
        glyphs[code and 255][y / 2] and (1 shl x) != 0
}
''')
