"""Extract numeric layout measurements only; never include CHR glyph/stroke data.
Usage: python measure-bgi-metrics.py <reference-font-directory> <output.kt>
Reference: gandrewstone/GameMaker/tools/BORLANDC/BGI (see third_party/bgi-fonts/PROVENANCE.md)
"""
from pathlib import Path
import hashlib
import struct
import sys

names = ['TRIP', 'LITT', 'SANS', 'GOTH', 'SCRI', 'SIMP', 'TSCR', 'LCOM', 'EURO', 'BOLD']
rows = []
heights = []
for name in names:
    data = (Path(sys.argv[1]) / (name + '.CHR')).read_bytes()
    if data[:4] != b'PK\x08\x08':
        raise ValueError('Not a BGI stroke font: ' + name)
    marker = data.index(b'\x1a')
    header = struct.unpack_from('<H', data, marker + 1)[0]
    if data[header] != ord('+'):
        raise ValueError('Missing stroke header: ' + name)
    count = struct.unpack_from('<H', data, header + 1)[0]
    first = data[header + 4]
    table = header + 16 + count * 2
    advances = list(data[table:table + count])
    if len(advances) != count or first + count > 256:
        raise ValueError('Invalid character widths: ' + name)
    widths = [advances[ord('?') - first]] * 256
    widths[first:first + count] = advances
    height = struct.unpack_from('b', data, header + 8)[0] - struct.unpack_from('b', data, header + 10)[0]
    heights.append(height)
    encoded = ''.join(f'{w:02x}' for w in widths)
    rows.append(f'        // {name}: reference SHA-256 {hashlib.sha256(data).hexdigest()}\n        "{encoded}"')
text = '''package com.infinifolder.preview

/** Numeric font layout measurements only; no font outlines or glyph data.
 * Generated by scripts/measure-bgi-metrics.py from the referenced RIPterm 1.54 fonts.
 * Font IDs 1..10; metrics retain proportional advances instead of an estimated cell width.
 */
internal object RipFontMetrics {
'''
text += '    private val heights=intArrayOf(' + ','.join(map(str, heights)) + ')\n'
text += '    private val advances=listOf(\n' + ',\n'.join(rows) + '\n    ).map {hex->IntArray(256){hex.substring(it*2,it*2+2).toInt(16)}}\n'
text += '''    fun height(font:Int)=heights[(font-1).coerceIn(0,9)]
    fun advance(font:Int,code:Int)=advances[(font-1).coerceIn(0,9)][code and 255]
}
'''
Path(sys.argv[2]).write_text(text)
